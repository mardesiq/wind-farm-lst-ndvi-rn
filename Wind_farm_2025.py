# Função para calcular NDVI
def calcular_ndvi_periodo(lat, lon, inicio, fim):
    ponto = ee.Geometry.Point([lon, lat])
    colecao = (
        ee.ImageCollection('MODIS/061/MOD13A1')
        .filterBounds(ponto)
        .filterDate(inicio, fim)
        .map(lambda img: img.updateMask(img.select('SummaryQA').eq(0)))
    )
    ndvi = colecao.select('NDVI').mean().reduceRegion(
        reducer=ee.Reducer.mean(),
        geometry=ponto,
        scale=500
    ).get('NDVI')

    valor = ndvi.getInfo()
    return valor * 0.0001 if valor is not None else None

