"""# ***LST (Land Surface Temperature)***
with Cloud Filtering

**Wind Turbines**

**Annual Daytime LST**
"""

import pandas as pd
import ee
import os
import csv
import time
from concurrent.futures import ThreadPoolExecutor, as_completed
from tqdm import tqdm

# Inicializar Earth Engine
try:
    ee.Initialize()
except Exception:
    ee.Authenticate()

# Configurações
INPUT_CSV = '/content/drive/MyDrive/UFRN/Artigo_Eólicas/aerogeradores_caatinga_clusterizado1.csv'
OUTPUT_DIR = '/content/drive/MyDrive/UFRN/Artigo_Eólicas/LST_Resultados/'
OUTPUT_FILE = os.path.join(OUTPUT_DIR, 'AERO_LSTDay_2003_2025.csv')
ANOS = list(range(2003, 2025))
BATCH_SIZE = 50  # Tamanho do lote para salvamento
MAX_WORKERS = 10  # Número de threads paralelas

# Criar diretório de saída
os.makedirs(OUTPUT_DIR, exist_ok=True)

# Colunas do arquivo de saída
COLUNAS = ['latitude', 'longitude', 'cluster'] + [f'LST_Dia_{ano}' for ano in ANOS]

## FUNÇÕES OTIMIZADAS ##

def processar_ano(ponto: ee.Geometry.Point, ano: int) -> float:
    """Processa um único ano para um ponto específico"""
    try:
        colecao = (ee.ImageCollection('MODIS/061/MOD11A1')
                  .filterBounds(ponto)
                  .filterDate(f'{ano}-01-01', f'{ano}-12-31')
                  .map(lambda img: img.updateMask(img.select('QC_Day').eq(0))))

        # Otimização: processar apenas a banda necessária
        media = (colecao.select('LST_Day_1km')
                .mean()
                .reduceRegion(
                    reducer=ee.Reducer.mean(),
                    geometry=ponto,
                    scale=1000,
                    maxPixels=1e13
                ).get('LST_Day_1km'))

        valor = media.getInfo()
        return valor * 0.02 - 273.15 if valor is not None else None

    except Exception as e:
        print(f"Erro no ano {ano}: {str(e)}")
        return None

def processar_ponto(row: dict) -> list:
    """Processa todos os anos para um ponto específico"""
    try:
        lat, lon = float(row['latitude']), float(row['longitude'])
        ponto = ee.Geometry.Point([lon, lat])

        resultados = []
        for ano in ANOS:
            resultado = processar_ano(ponto, ano)
            resultados.append(resultado)
            time.sleep(0.1)  # Pequena pausa entre requisições

        return [lat, lon, row.get('cluster', None)] + resultados

    except Exception as e:
        print(f"Erro ao processar ponto ({row['latitude']}, {row['longitude']}): {str(e)}")
        return None

## PROCESSAMENTO PRINCIPAL ##

def main():
    # Carregar dados de entrada
    try:
        df = pd.read_csv(INPUT_CSV)
        df.columns = df.columns.str.strip().str.lower()

        if 'latitude' not in df.columns or 'longitude' not in df.columns:
            raise ValueError("O CSV precisa ter colunas 'latitude' e 'longitude'")

        print(f"Total de pontos a processar: {len(df)}")
    except Exception as e:
        print(f"Erro ao carregar CSV: {str(e)}")
        return

    # Verificar resultados existentes
    if os.path.exists(OUTPUT_FILE) and os.path.getsize(OUTPUT_FILE) > 0:
        try:
            df_existente = pd.read_csv(OUTPUT_FILE)
            df_existente.columns = df_existente.columns.str.strip().str.lower()
            coordenadas_processadas = set(zip(
                df_existente['latitude'].round(6),
                df_existente['longitude'].round(6)
            ))
            print(f"Carregados {len(df_existente)} pontos existentes")
        except Exception as e:
            print(f"Erro ao carregar arquivo existente: {str(e)}")
            coordenadas_processadas = set()
    else:
        coordenadas_processadas = set()
        with open(OUTPUT_FILE, mode='w', newline='') as f:
            csv.writer(f).writerow(COLUNAS)

    # Filtrar pontos não processados
    pontos_para_processar = []
    for _, row in df.iterrows():
        lat = round(float(row['latitude']), 6)
        lon = round(float(row['longitude']), 6)
        if (lat, lon) not in coordenadas_processadas:
            pontos_para_processar.append({
                'latitude': lat,
                'longitude': lon,
                'cluster': row.get('cluster', None)
            })

    print(f"Pontos restantes para processar: {len(pontos_para_processar)}")

    # Processamento paralelo
    resultados = []
    with ThreadPoolExecutor(max_workers=MAX_WORKERS) as executor:
        futures = {executor.submit(processar_ponto, row): row for row in pontos_para_processar}

        for future in tqdm(as_completed(futures), total=len(futures), desc="Processando pontos"):
            resultado = future.result()
            if resultado:
                resultados.append(resultado)

                # Salvamento em lotes
                if len(resultados) >= BATCH_SIZE:
                    with open(OUTPUT_FILE, mode='a', newline='') as f:
                        writer = csv.writer(f)
                        writer.writerows(resultados)
                    resultados = []

    # Salvar resultados restantes
    if resultados:
        with open(OUTPUT_FILE, mode='a', newline='') as f:
            csv.writer(f).writerows(resultados)

    print(f"\n✅ Processamento concluído! Arquivo salvo em: {OUTPUT_FILE}")

if __name__ == "__main__":
    main()

""" **Annual Nighttime LST**"""

import pandas as pd
import ee
import os
import csv
import time
from concurrent.futures import ThreadPoolExecutor, as_completed
from tqdm import tqdm

# Inicializar Earth Engine
try:
    ee.Initialize()
except Exception:
    ee.Authenticate()
# Caminhos
input_csv = '/content/drive/MyDrive/UFRN/Artigo_Eólicas/aerogeradores_caatinga_clusterizado1.csv'
output_directory = '/content/drive/MyDrive/UFRN/Artigo_Eólicas/LST_Resultados/'
