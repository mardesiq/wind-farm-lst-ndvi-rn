# --- Filtering to create DataFrames for each altitude range ---
# O filtro original usava 500m. Mantenho o filtro, mas renomeio a variável para 500m para clareza.
df_700m = df_grouped[df_grouped['altitude'] <= 700].copy() # .copy() para evitar SettingWithCopyWarning
df_500m = df_grouped[df_grouped['altitude'] <= 500].copy()

# NOVO: Adicionando coluna de Categoria para o scatter plot (apenas para o range de 700m)
# Isso permite colorir os pontos que estão no range 500-700m
df_700m.loc[:, 'altitude_category'] = np.where(
    df_700m['altitude'] <= 500,
    '<= 500m',
    '> 500m'
)


# --- Plotting Function UPDATED for separate scatter and regplot calls (English Labels) ---
def plot_regression_two_lines_fixed(ax, x, y, data_700m_full, data_500m_reg, title, xlabel, ylabel):

    # 1. Plotar os pontos de dispersão (scatter) APENAS UMA VEZ, diferenciados por cor
    sns.scatterplot(
        data=data_700m_full,
        x=x,
        y=y,
        ax=ax,
        hue='altitude_category',
        palette={'<= 500m': 'darkred', '> 500m': 'darkblue'}, # Cores distintas para os pontos
        s=70,
        alpha=0.8,
        legend=False # A legenda será gerada pelos regplots
    )

    # 2. Plotar a linha de regressão para altitudes até 700m (azul)
    if not data_700m_full.empty and len(data_700m_full) > 1:
        r_700, _ = pearsonr(data_700m_full[x], data_700m_full[y])
        label_700 = f"<= 700m (R = {r_700:.2f})"

        sns.regplot(data=data_700m_full, x=x, y=y, ax=ax,
                    scatter=False, # Não plota os pontos
                    line_kws={'color': 'blue', 'linewidth': 2},
                    label=label_700, ci=95)
    else:
        ax.text(0.5, 0.6, "Insufficient data for 700m", ha="center", va="center", transform=ax.transAxes)

    # 3. Plotar a linha de regressão para altitudes até 500m (vermelha)
    if not data_500m_reg.empty and len(data_500m_reg) > 1:
        r_500, _ = pearsonr(data_500m_reg[x], data_500m_reg[y])
        label_500 = f"<= 500m (R = {r_500:.2f})"

        sns.regplot(data=data_500m_reg, x=x, y=y, ax=ax,
                    scatter=False, # Não plota os pontos
                    line_kws={'color': 'red', 'linewidth': 2},
                    label=label_500, ci=95)
    else:
        ax.text(0.5, 0.5, "Insufficient data for 500m", ha="center", va="center", transform=ax.transAxes)

    # Final adjustments
    ax.set_title(title)
    ax.set_xlabel(xlabel)
    ax.set_ylabel(ylabel)
    ax.legend(loc='best', frameon=True)


