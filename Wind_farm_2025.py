import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from sklearn.neighbors import NearestNeighbors
from kneed import KneeLocator
from sklearn.cluster import DBSCAN

#Cluster por distância apenas
# Carregar CSV
csv_path = '/content/drive/MyDrive/UFRN/Artigo_Eólicas/SHPs/SHP_cluster_distancia/pontos1.csv'
df = pd.read_csv(csv_path)

# Extrair coordenadas
coords = df[['longitude', 'latitude']].to_numpy()

# Calcular as distâncias dos k vizinhos mais próximos
k = 11
nearest_neighbors = NearestNeighbors(n_neighbors=k)
neighbors = nearest_neighbors.fit(coords)
distances, indices = neighbors.kneighbors(coords)

# Ordenar as distâncias do 10º vizinho (índice k-1)
distances = np.sort(distances[:, k - 1], axis=0)

# Plotar a curva de distâncias
plt.figure(figsize=(6, 4))
plt.plot(distances)
plt.xlabel("Pontos ordenados")
plt.ylabel("Distância")
plt.title("Curva de Distância - Vizinhos mais próximos")
plt.grid(True)
plt.savefig("Distance_curve.png", dpi=300)
plt.show()

# Encontrar o ponto de cotovelo
i = np.arange(len(distances))
knee = KneeLocator(i, distances, S=1.0, curve='convex', direction='increasing', interp_method='polynomial')

# Visualizar o ponto de cotovelo
knee.plot_knee()
plt.xlabel("Pontos ordenados")
plt.ylabel("Distância")
plt.title("Ponto de Cotovelo (eps ideal)")
plt.grid(True)
plt.show()

# Valor ideal de eps
eps = distances[knee.knee]
print(f"✅ Valor ideal de eps: {eps}")

# Aplicar DBSCAN com eps e min_samples ajustáveis
# Exemplo de configuração inicial: eps baseado no cotovelo e min_samples = 5
db = DBSCAN(eps=eps, min_samples=5).fit(coords)
labels = db.labels_

# Adicionar rótulos de cluster ao DataFrame
df['cluster'] = labels

# Relatório
n_clusters = len(set(labels)) - (1 if -1 in labels else 0)
n_noise = list(labels).count(-1)

print(f"📦 Número estimado de clusters: {n_clusters}")
print(f"🗑️ Número de pontos de ruído: {n_noise}")

# Salvar o resultado em CSV
saida_csv = '/content/drive/MyDrive/UFRN/Artigo_Eólicas/SHPs/SHP_cluster_distancia/aerogeradores_caatinga_clusterizado1.csv'
