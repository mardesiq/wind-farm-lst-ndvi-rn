os.makedirs(output_directory, exist_ok=True)

# Parâmetros
ANOS = list(range(2003, 2025))
BATCH_SIZE = 50
MAX_WORKERS = 10
COLUNAS = ['latitude', 'longitude', 'cluster'] + [f'LST_Night_{ano}' for ano in ANOS]

def processar_ano(ponto: ee.Geometry.Point, ano: int) -> float:
    """Extrai a média anual de LST noturna em ºC"""
    try:
        colecao = (
            ee.ImageCollection('MODIS/061/MOD11A1')
            .filterBounds(ponto)
            .filterDate(f'{ano}-01-01', f'{ano}-12-31')
            # Manter apenas qualidade "boa" (bit 0 e 1 com valor 01 ou 00 → qualidade aceitável)
            .map(lambda img: img.updateMask(
                img.select('QC_Night').bitwiseAnd(3).lte(1)
            ))
        )

        media = colecao.select('LST_Night_1km').mean()

        resultado = media.reduceRegion(
            reducer=ee.Reducer.mean(),
            geometry=ponto,
            scale=1000,
            maxPixels=1e13
        ).get('LST_Night_1km')

        if resultado is not None:
            valor = resultado.getInfo()
            return round(valor * 0.02 - 273.15, 2) if valor is not None else None
        return None

    except Exception as e:
        print(f"[Erro] Ano {ano}: {str(e)}")
        return None

def processar_ponto(row: dict) -> list:
    """Processa um ponto para todos os anos"""
    try:
        ponto = ee.Geometry.Point([float(row['longitude']), float(row['latitude'])])
        resultados = [float(row['latitude']), float(row['longitude']), row.get('cluster')]

        for ano in ANOS:
            lst = processar_ano(ponto, ano)
            resultados.append(lst)
            time.sleep(0.1)

        return resultados

    except Exception as e:
        print(f"[Erro] Ponto ({row['latitude']}, {row['longitude']}): {str(e)}")
        return None

def main():
    try:
        df = pd.read_csv(input_csv)
        df.columns = df.columns.str.strip().str.lower()
        print(f"🔍 Total de pontos no CSV: {len(df)}")
    except Exception as e:
        print(f"[Erro] Falha ao carregar CSV: {str(e)}")
        return

    # Verificar dados já processados
    if os.path.exists(output_file) and os.path.getsize(output_file) > 0:
        try:
            df_existente = pd.read_csv(output_file)
            coordenadas_processadas = set(zip(
                df_existente['latitude'].round(6),
                df_existente['longitude'].round(6)
            ))
            print(f"✅ Pontos já processados: {len(coordenadas_processadas)}")
        except Exception as e:
            print(f"[Aviso] Não foi possível carregar saída existente: {str(e)}")
            coordenadas_processadas = set()
    else:
        with open(output_file, 'w', newline='') as f:
            csv.writer(f).writerow(COLUNAS)
        coordenadas_processadas = set()

    # Filtrar pontos ainda não processados
    novos_pontos = []
    for _, row in df.iterrows():
        lat, lon = round(float(row['latitude']), 6), round(float(row['longitude']), 6)
        if (lat, lon) not in coordenadas_processadas:
            novos_pontos.append(row.to_dict())

    print(f"🟡 Novos pontos a processar: {len(novos_pontos)}")

    resultados = []
    with ThreadPoolExecutor(max_workers=MAX_WORKERS) as executor:
        futures = {executor.submit(processar_ponto, row): row for row in novos_pontos}

        for future in tqdm(as_completed(futures), total=len(futures), desc="Processando pontos"):
            resultado = future.result()
            if resultado:
                resultados.append(resultado)

                if len(resultados) >= BATCH_SIZE:
                    with open(output_file, 'a', newline='') as f:
                        csv.writer(f).writerows(resultados)
                    resultados = []
                    print(f"💾 Lote salvo com {BATCH_SIZE} pontos")

    # Salvar o restante
    if resultados:
        with open(output_file, 'a', newline='') as f:
            csv.writer(f).writerows(resultados)
        print(f"💾 Lote final salvo com {len(resultados)} pontos")

    print(f"\n✅ Processamento concluído. Arquivo em: {output_file}")

if __name__ == "__main__":
    main()

