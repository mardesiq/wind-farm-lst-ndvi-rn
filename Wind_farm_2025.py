# === 6. Função para cálculo de NDVI anual ===
def calcular_ndvi_anual(ano):
    inicio = ee.Date.fromYMD(ano, 1, 1)
    fim = ee.Date.fromYMD(ano, 12, 31)
    # Escala do MODIS é 0.0001
    ndvi_ano = modis.filterDate(inicio, fim).mean().multiply(0.0001)

    resultado = ndvi_ano.reduceRegions(
        collection=fc,
        reducer=ee.Reducer.mean(),
        scale=500
    ).map(lambda f: f.set('ano', ano))
    return resultado

