# Função para obter LST com tratamento de erros
# =========================================================
def get_lst_period(point, start_date, end_date, day_night):
    """Obtém a média da LST para um ponto e período, com tratamento de erros."""
    max_retries = 3

    for attempt in range(max_retries):
        try:
            # Coleção MODIS/061/MOD11A2
            lst_collection = ee.ImageCollection("MODIS/061/MOD11A2") \
                .filterDate(start_date, end_date) \
                .filterBounds(point) \
                .select(day_night)

            # Se não houver imagens na coleção, retorna None
            if lst_collection.size().getInfo() == 0:
                 return None

            lst = lst_collection.mean() \
                .reduceRegion(ee.Reducer.mean(), point, 1000) \
                .get(day_night) \
                .getInfo()

            # A fórmula de conversão de Kelvin para Celsius (já estava correta)
            return (lst * 0.02) - 273.15 if lst is not None else None

        except ee.EEException as e:
            # Erro específico do Earth Engine (ex: limite de taxa ou timeout)
            print(f"⚠️ Erro no EE (Tentativa {attempt+1}/{max_retries}): {e}. Aguardando...")
            time.sleep(5) # Aguarda 5 segundos antes de tentar novamente
            if attempt == max_retries - 1:
                print(f"Erro persistente no ponto: {point.getInfo()} - pulando.")
                return None
        except Exception as e:
            # Outros erros
            print(f"❌ Erro geral ao obter LST ({day_night}): {e}")
            return None

