# --- 5. GEE Batch Processing Function ---
def get_ndvi_for_points_yearly(points_df, year):
    """
    Calculates the annual mean NDVI for a collection of points for a given year,
    applying a quality mask.
    """
    features = []
    for _, row in points_df.iterrows():
        point_id = row['original_index'] # Use original index to link back
        geom = ee.Geometry.Point([row['longitude'], row['latitude']])
        features.append(ee.Feature(geom, {'id': point_id}))

    feature_collection = ee.FeatureCollection(features)

    # Filter MODIS MOD13A1 collection for the year
    collection = ee.ImageCollection('MODIS/061/MOD13A1') \
        .filterDate(f'{year}-01-01', f'{year}-12-31') \
        .map(lambda img: img.updateMask(img.select('SummaryQA').eq(0))) \
        .select('NDVI')

    # Compute mean NDVI for the year
    mean_ndvi_image = collection.mean()

    # Reduce regions to get NDVI values at each point
    # Use a safe scale, e.g., 500m for MODIS
    reduced_fc = mean_ndvi_image.reduceRegions(
        collection=feature_collection,
        reducer=ee.Reducer.mean(),
        scale=500
    )

    results = {}
    try:
        # Fetch results
        gee_results = reduced_fc.getInfo()
        for feature in gee_results['features']:
            point_id = feature['properties']['id']
            ndvi_value = feature['properties'].get('mean', None) # 'mean' is the default name for ee.Reducer.mean()
            # Scale NDVI to 0-1 range if not None
            results[point_id] = ndvi_value * 0.0001 if ndvi_value is not None else None
    except Exception as e:
        print(f"Error fetching GEE results for year {year}: {e}")
        # If an error occurs, return None for all points in this year
        for _, row in points_df.iterrows():
            results[row['original_index']] = None
    return results

