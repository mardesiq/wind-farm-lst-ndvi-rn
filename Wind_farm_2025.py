    output_file = OUTPUT_DIR / f'lst_{estacao.lower()}_{tipo.lower()}_2003_2025.csv'
    colunas = ['latitude', 'longitude', 'cluster'] + [f'LST_{estacao}_{tipo}_{ano}' for ano in ANOS]

    processados = set()
    if output_file.exists():
        try:
            df_existente = pd.read_csv(output_file)
            processados = set(zip(df_existente['latitude'], df_existente['longitude']))
        except Exception as e:
            print(f"[⚠️ ERRO] Falha ao ler arquivo existente: {e}")

    else:
        # Cria cabeçalho apenas se o arquivo ainda não existir
        with open(output_file, mode='w', newline='') as f:
            csv.writer(f).writerow(colunas)

    resultados_buffer = []
    num_pontos = len(df)
    futures = []

    with ThreadPoolExecutor(max_workers=MAX_WORKERS) as executor:
        for _, row in df.iterrows():
            lat, lon = float(row['latitude']), float(row['longitude'])
            if (lat, lon) in processados:
                continue
            futures.append(executor.submit(processar_ponto, row, tipo, estacao, meses))

