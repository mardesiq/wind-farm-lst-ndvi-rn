def get_elevation_from_ee(latitude: float, longitude: float):
    """
    Obtains the elevation of a coordinate using the Earth Engine SRTM model.
    """
    try:
        point = ee.Geometry.Point([longitude, latitude])
        elevation_image = ee.Image('USGS/SRTMGL1_003')
        elevation_value = elevation_image.sample(point, 30).first().get('elevation').getInfo()
        return elevation_value
    except Exception as e:
        print(f"Error obtaining elevation for ({latitude}, {longitude}): {e}")
        return None

def processar_e_adicionar_elevacao(caminho_csv_original: str):
    """
    Reads a CSV, adds the elevation, and saves it to a new file.
    It checks if the processed file already exists to avoid recalculation.
    """
    output_path = caminho_csv_original.replace('.csv', '_com_elevacao_real.csv')

    # Check if the processed file already exists
    if os.path.exists(output_path):
        print(f"✅ Processed file already exists: {output_path}. Skipping elevation calculation.")
        return output_path

    print(f"Starting elevation processing for: {os.path.basename(caminho_csv_original)}")
    df = pd.read_csv(caminho_csv_original)

    # Ensure that the coordinate column names are standardized
    df.columns = df.columns.str.strip().str.lower()

    # Identify and group the unique points
    pontos_unicos_df = df[['latitude', 'longitude']].drop_duplicates().reset_index(drop=True)

    elevacoes_cache = {}
    for row in tqdm(pontos_unicos_df.itertuples(), total=len(pontos_unicos_df), desc="Calculating Elevation"):
        lat = row.latitude
        lon = row.longitude
        elevacao = get_elevation_from_ee(lat, lon)
        elevacoes_cache[(lat, lon)] = elevacao

    # Map the elevations back to the original DataFrame
    df['elevation'] = df.apply(lambda r: elevacoes_cache.get((r['latitude'], r['longitude'])), axis=1)

    # Save the new file
    df.to_csv(output_path, index=False)
    print(f"✅ Elevation added and saved to: {output_path}")
    return output_path

