# --- CONVERSÃO QC ---
def aplicar_mascara_qc(img, qc_banda):
    """
    Aplica máscara de controle de qualidade (QC) para imagens MODIS LST.
    Bits 0 e 1 de 'QC_Day' ou 'QC_Night' indicam a qualidade dos dados LST.
    00 = LST produzida, boa qualidade, sem contaminação por nuvens ou outras
    01 = LST produzida, qualidade média, contaminação de nuvens ou outras
    10 = LST não produzida devido a nuvens (ver bits 2 e 3 para mais detalhes)
    11 = LST não produzida devido a outras razões (ver bits 2 e 3 para mais detalhes)
    Retorna apenas pixels com qualidade boa (0) ou média (1).
    """
    qc = img.select(qc_banda)
    qualidade = qc.bitwiseAnd(3)  # Extrai os bits 0 e 1
    return img.updateMask(qualidade.lte(1))  # Mascara pixels com qualidade inferior a 1 (boa ou média)

# --- OBTÉM LST POR ESTAÇÃO ---
def obter_lst_sazonal(ponto, ano, tipo, meses):
    """
    Obtém a Temperatura da Superfície Terrestre (LST) sazonal para um ponto e ano específicos.
    """
    banda = 'LST_Day_1km' if tipo == 'Day' else 'LST_Night_1km'
    qc_banda = 'QC_Day' if tipo == 'Day' else 'QC_Night'

    # Formatação de data mais robusta, garantindo dois dígitos para o mês
    data_inicio = f'{ano}-{min(meses):02d}-01'
    data_fim = f'{ano}-{max(meses):02d}-28' # Usar 28 para evitar problemas com meses de 30/31 dias

    try:
        colecao = (ee.ImageCollection('MODIS/061/MOD11A1')
                   .filterBounds(ponto)
                   .filterDate(data_inicio, data_fim)
                   .map(lambda img: aplicar_mascara_qc(img, qc_banda)))

        # Não é necessário chamar getInfo() para o count aqui.
        # Se a coleção estiver vazia, .mean() retornará uma imagem nula,
        # e .reduceRegion().get(banda) retornará None, o que já é tratado.

        media = (colecao.select(banda)
                         .mean()
                         .reduceRegion(
                             reducer=ee.Reducer.mean(),
                             geometry=ponto,
                             scale=1000,
                             maxPixels=1e13
                         ).get(banda))

        valor = media.getInfo() # getInfo() é a chamada que gasta mais tempo e recursos
        if valor is not None:
            return valor * 0.02 - 273.15  # Converte para Celsius
        else:
            # Não é necessário imprimir "[SEM RESULTADO REDUCE]" aqui.
            # O retorno None já indica a ausência de valor.
            return None

    except ee.EEException as e:
        # Captura erros específicos do Earth Engine, como "User Rate Limit Exceeded"
        print(f"[ERRO GEE] {tipo}, {ano}, ponto {ponto.getInfo()['coordinates']} - {e}")
        return None
    except Exception as e:
        print(f"[ERRO GERAL] {tipo}, {ano}, ponto {ponto.getInfo()['coordinates']} - {e}")
        return None

# --- PROCESSAR PONTO ---
def processar_ponto(row, tipo, estacao, meses):
    """
    Processa um único ponto (latitude, longitude) para todas as combinações de ano, tipo e estação.
    """
    lat, lon = float(row['latitude']), float(row['longitude'])
    ponto = ee.Geometry.Point([lon, lat])
    # Usar .get() com um valor padrão para 'cluster' para evitar KeyError se a coluna não existir
    resultados_ponto = [lat, lon, row.get('cluster', 'N/A')] # 'N/A' como valor padrão

    for ano in ANOS:
        lst = obter_lst_sazonal(ponto, ano, tipo, meses)
        resultados_ponto.append(lst)
    return resultados_ponto

