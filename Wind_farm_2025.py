def get_altitudes_batch(df):
    """Retorna o DataFrame com coluna 'altitude' preenchida usando GEE SRTM"""
    features = []
    for _, row in df.iterrows():
        geom = ee.Geometry.Point([row['longitude'], row['latitude']])
        feat = ee.Feature(geom, {'cluster': row['cluster']})
        features.append(feat)

    fc = ee.FeatureCollection(features)

    # Imagem SRTM
    dem = ee.Image("USGS/SRTMGL1_003")
    sampled = dem.sampleRegions(collection=fc, scale=30, geometries=True)

    # Transformar em lista Python
    data = sampled.getInfo()['features']

    # Extrair resultados
    results = []
    for f in data:
        lon, lat = f['geometry']['coordinates']
        alt = f['properties']['elevation']
        results.append({
            'cluster': f['properties']['cluster'],
            'longitude': lon,
            'latitude': lat,
            'altitude': alt
        })

    return pd.DataFrame(results)

